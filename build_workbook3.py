def sheet(name, title, widths, headers, rows, *, freeze="A4", notes=None,
          center_cols=()):
    ws = wb.create_sheet(name)
    ws["A1"] = title
    ws["A1"].font = TITLE_FONT
    ws.merge_cells(start_row=1, start_column=1, end_row=1,
                   end_column=max(len(headers), 2))
    ws["A2"] = (f"项目 8.1 振动状态监测器 · 受控文档台账　|　版本 {VERSION}　|　"
                f"更新日期 {TODAY}　|　维护人：P1")
    ws["A2"].font = NOTE_FONT
    ws.merge_cells(start_row=2, start_column=1, end_row=2,
                   end_column=max(len(headers), 2))
    for i, htxt in enumerate(headers, start=1):
        c = ws.cell(row=3, column=i, value=htxt)
        c.fill = HDR_FILL
        c.font = HDR_FONT
        c.alignment = CENTER
        c.border = BORDER
    for r, row in enumerate(rows, start=4):
        for i, v in enumerate(row, start=1):
            c = ws.cell(row=r, column=i, value=v)
            c.font = BODY
            c.border = BORDER
            c.alignment = CENTER if i in center_cols else WRAP
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = freeze
    last = 3 + len(rows)
    ws.auto_filter.ref = f"A3:{get_column_letter(len(headers))}{last}"
    if notes:
        ws.cell(row=last + 2, column=1, value=notes).font = NOTE_FONT
    return ws


