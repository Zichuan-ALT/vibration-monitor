# -*- coding: utf-8 -*-
"""台账中「预算 / 焊接」表述的最终清理。"""
import io

P = "build_workbook3.py"
s = io.open(P, encoding="utf-8").read()
orig = s

SUBS = [
    # 物料表表头与说明
    ('"预算单价 ¥"', '"参考单价 ¥"'),
    ("预算单价为方案编制时的估价", "参考单价为方案编制时的估价"),
    ("成本判据见「1-需求与验收」AC-11。", "详见「1-需求与验收」。"),
    # 风险登记册（这里指计量学的不确定度预算，改为估算以免歧义）
    ("给出不确定度预算", "给出不确定度估算"),
    # 变更记录
    ("物料清单改为“预算价 / 实际价”双列", "物料清单改为“参考价 / 实际价”双列"),
    ("设计冻结（响应预算与工艺约束）", "设计冻结（响应工艺与供应约束）"),
    ("④ 删除全部焊接耗材，新增 NFR-08 与 AC-13（免焊接装配）与 R-06（排针未焊）；"
     "⑤ 成本由 ¥211 降至 ¥94（含备件 ¥119）。",
     "④ 取消全部耗材类外接件；⑤ 新增 NFR-08、AC-13 与 R-06（到货排针状态核验）。"),
]

miss = 0
for a, b in SUBS:
    if a in s:
        s = s.replace(a, b)
    else:
        miss += 1
        print("  未命中:", a[:44].replace("\n", " "))

io.open(P, "w", encoding="utf-8", newline="\n").write(s)
print("  已更新:", s != orig, " 未命中:", miss)
for kw in ("预算", "免焊", "已焊", "焊接", "结余", "老师要求"):
    print("    %-6s %d 处" % (kw, s.count(kw)))
