h("6.3.5  意义", 3)
para("这次经历说明，支撑刚度对振动测量的影响（3.7 倍）远大于传感器粘接质量。"
     "根本原因是：传感器无法区分「设备自身的结构振动」与「设备整体的刚体运动」。"
     "工业标准要求振动测量必须相对于刚性基础进行，机组基础须有足够刚度，"
     "原因正在于此。", indent=True)
para("对方法论的启示更值得记录：当怀疑某个因素时，应设计能**只改变该因素**的实验；"
     "若两个变量同时被改变，即便结果「符合预期」，也不能作为证据。", indent=True)

