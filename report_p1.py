h("3.3.4  状态判定策略", 3)
para("判定采用「基线自学习 + 迟滞」的方式，不使用固定阈值。原因很直接："
     "同一台设备在不同安装状态下的振动水平可以相差 3 倍以上（见 6.3 节实测），"
     "任何固定阈值都必然在某些场合误报或漏报。", indent=True)
para("设备上电后先采集 15 帧，计算带内 RMS 的均值 μ 与标准差 σ，"
     "随后令「注意」阈值为 μ+3σ、「报警」阈值为 μ+6σ。"
     "为避免抖动，状态升级需连续 3 帧确认、降级需连续 5 帧确认。"
     "此外增加一条保护：若自学习得到的 μ 小于 0.010 g，说明设备可能未运行或"
     "传感器脱落，此时拒绝该基线并将状态置为「未标定」，而不是带着错误的阈值工作。", indent=True)

