h("3.3  信号处理设计", 2)
para("本节说明三个核心参数是怎么定下来的：采样率、帧长、以及为什么必须带限计算 RMS。"
     "这三项直接决定了后续所有数据的可信度。", indent=True)

h("3.3.1  采样参数", 3)
para("状态监测关心的振动成分主要在 10~260 Hz：过低是支撑与整体运动，"
     "过高则超出小型风机的激励范围。按 Nyquist 定理，采样率至少为分析带宽的 2 倍，"
     "本方案取 1 kHz，留约 4 倍余量，同时也让 MPU6050 内部 256 Hz 低通滤波器的"
     "过渡带落在有效带宽之外。", indent=True)
para("帧长取 1024 点，对应频率分辨率 Δf = fs/N = 0.977 Hz，帧长 1.024 s。"
     "这是分辨率与实时性的折中：帧再长，频率分辨率更高但报警更迟钝；"
     "帧再短，1× 转频与相邻谐波就分不开。实测风扇转频约 34 Hz，"
     "相邻谐波间隔也是 34 Hz，0.977 Hz 的分辨率足以区分。", indent=True)
para("量程取 ±4 g（8192 LSB/g）。选择依据是后文的不平衡实验：0.7 g 配重时"
     "峰值约 3.2 g，若取 ±2 g 会削顶，若取 ±8 g 则分辨率减半。")

h("3.3.2  为什么必须带限计算 RMS", 3)
para("这是本项目在实现过程中修正的一个设计。最初的做法是对整段时域信号直接求 RMS，"
     "结果发现：风扇停转、模块静止放置时，RMS 仍有 0.05 g 左右，"
     "而按传感器噪声密度推算应当只有 0.005 g，相差 10 倍。", indent=True)
para("原因在于设备并非绝对静止——桌面会因人员走动、建筑振动而轻微运动，"
     "这些低频成分（< 10 Hz）被完整地算进了 RMS。它们与「设备自身的振动」"
     "完全是两回事。修正办法是：先做 FFT，再在幅度谱上按 Parseval 定理"
     "只累加 10~260 Hz 频段内的能量：", indent=True)
code_block([
    "RMS_band = sqrt( Σ_{f ∈ [10, 260] Hz}  A_k² / 2 )",
    "",
    "其中 A_k 为单边幅度谱第 k 条谱线的峰值幅度（Hann 窗相干增益 0.5，需乘 2 修正）",
])
para("修正后，静止状态的 RMS 降到 0.0053 g，与传感器噪声水平一致；"
     "而风扇运转时仍为 0.05~0.09 g，信号与噪声的区分度反而更高。"
     "这条经验说明：RMS 这种「看起来最朴素」的统计量，也必须先明确"
     "「要统计什么频段」。")

