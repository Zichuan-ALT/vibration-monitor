h("10.2  主要工作与发现", 2)
para("本报告认为有三项工作值得强调。", indent=True)
para("第一，完成了从传感器到仪表板的完整链路，并用真实故障（不平衡、堵塞）"
     "验证了系统的识别能力。两次故障实验都给出了三级工况的实测数据与频谱证据，"
     "不是仿真结果。", indent=True)
para("第二，实测并量化了「支撑刚度」对振动测量的影响（3.7 倍），"
     "并由此给出一个可用的在线判别指标（1× 峰值 / 带内 RMS）。"
     "更重要的是记录了一次因变量混淆导致的误判——按压传感器时同时改变了"
     "结构阻尼，使结论指向错误方向。这一过程比结论本身更有方法论价值。", indent=True)
para("第三，通过风道堵塞实验验证了双通道设计的必要性：堵塞使温度上升 0.6~0.8 ℃、"
     "而振动反而下降约 30%。若只有振动传感器，系统会把这种劣化误判为"
     "「状态改善」，故障被完全掩盖。两类故障的特征方向相反，"
     "这正是「至少两路有意义的数据输入」的实际含义。", indent=True)

